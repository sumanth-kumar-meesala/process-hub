import { Version } from '@microsoft/sp-core-library';
import { BaseClientSideWebPart } from '@microsoft/sp-webpart-base';
import appHtml from './appHtml'; // generated by prebuild.mjs from the Vite single-file build

// ponytail: the app runs unchanged in an iframe (srcdoc): its Tailwind styles can't leak into the SharePoint page,
// and the frame shares SharePoint's origin, so IndexedDB and the REST calls with the viewer's own sign-in work.
export default class ProcessHubWebPart extends BaseClientSideWebPart<Record<string, never>> {
  public render(): void {
    const frame = document.createElement('iframe');
    frame.title = 'Process Hub';
    frame.srcdoc = appHtml;
    frame.setAttribute('style', 'width:100%;height:88vh;min-height:720px;border:0;display:block');
    this.domElement.replaceChildren(frame);
  }

  protected get dataVersion(): Version {
    return Version.parse('1.0');
  }
}
